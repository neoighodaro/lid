package backend

import (
	"fmt"
	"sort"
	"strings"

	"github.com/neoighodaro/lid/internal/config"
)

// shellRC is the init file an interactive 'lid shell' starts under. It replaces
// ~/.bashrc for that session, so it sources it first: the shell: block adds to
// what the user already has rather than taking it away.
func shellRC(cfg *config.Config, dir string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by lid from %s. Edit the shell: block, not this file.\n", cfg.Ref())
	b.WriteString("[ -f \"$HOME/.bashrc\" ] && . \"$HOME/.bashrc\"\n")

	names := make([]string, 0, len(cfg.Shell.Aliases))
	for name := range cfg.Shell.Aliases {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		fmt.Fprintf(&b, "alias %s=%s\n", name, shellQuote(cfg.Shell.Aliases[name]))
	}

	if dir != "" {
		fmt.Fprintf(&b, "cd %s\n", shellQuote(dir))
	}
	return b.String()
}

// shellDir is where a shell session starts: the configured directory, or the
// backend's own idea of the project root when the shell: block is silent.
func shellDir(cfg *config.Config, fallback string) string {
	if cfg.Shell.Directory != "" {
		return cfg.Shell.Directory
	}
	return fallback
}

// shellCommandLine folds an argv back into one line for a shell to parse, so a
// word the user quoted on their own command line stays one word inside the
// sandbox. Bare words are left alone to keep the line readable in errors.
func shellCommandLine(command []string) string {
	words := make([]string, 0, len(command))
	for _, word := range command {
		if strings.ContainsAny(word, " \t\n'\"\\$`&|;<>()*?[]{}#~!") || word == "" {
			word = shellQuote(word)
		}
		words = append(words, word)
	}
	return strings.Join(words, " ")
}

// shellQuote wraps s so it survives as one literal argument.
func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
