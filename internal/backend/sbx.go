type sbx struct{}

func (sbx) Name() string { return config.BackendSbx }

func (sbx) EnsureAvailable(h Host) error {
	for _, name := range []string{"sbx", "docker"} {
		if _, err := h.lookPath(name); err != nil {
			return failure.New("%s is not installed", name).
				WithFix("install Docker Sandboxes from https://docs.docker.com/ai/sandboxes/, or set 'backend: %s' to cage a host process instead", config.BackendNono)
		}
	}
	return nil
}

func (sbx) Validate(cfg *config.Config) ([]string, error) {
	if _, err := cfg.ResolvedEnv(); err != nil {
		return nil, err
	}

	_, hasPHP := cfg.Runtimes["php"]
	warnings := handoffAgentWarning(cfg)
	for _, entry := range template.MissingMarketplaces(cfg) {
		warnings = append(warnings, fmt.Sprintf("skipping marketplace %s: it has no .claude-plugin/marketplace.json, so plugins from it are not installed", entry))
	}
	for _, group := range []struct {
		why    string
		fields []field
	}{
		{fmt.Sprintf("the %s agent gets no agent-specific setup", cfg.Agent), []field{
			{"claude", cfg.Claude.IsSet() && !config.IsClaudeAgent(cfg.Agent)},
			{"memory", cfg.Memory != "" && !config.IsClaudeAgent(cfg.Agent)},
		}},
		{"nothing installs them without the php runtime", []field{
			{"php.extensions", len(cfg.PHP.Extensions) > 0 && !hasPHP},
		}},
	} {
		if set := fieldsSet(group.fields); set != "" {
			warnings = append(warnings, fmt.Sprintf("ignoring %s: %s", set, group.why))
		}
	}
	return warnings, nil
}

func (s sbx) Render(cfg *config.Config) (string, error) {
	dockerfile, err := template.Render(cfg)
	if err != nil {
		return "", err
	}

	var b strings.Builder
	b.WriteString(dockerfile)
	b.WriteString(fmt.Sprintf("\n# Generated by lid from %s. 'lid start' then runs:\n", cfg.Ref()))
	for _, argv := range append(sbxSteps(cfg), s.startArgv(cfg)) {
		b.WriteString("#   " + sbxCommandLine(argv) + "\n")
	}
	return b.String(), nil
}

func (s sbx) Provision(h Host, cfg *config.Config, opts Options) (Provisioned, error) {
	image := sbxImage(cfg)
	hash, err := cfg.FileHash()
	if err != nil {
		return Provisioned{}, err
	}

	if sbxExists(h, cfg) {
		if !opts.Rebuild {
			current, err := sbxCurrentHash(h, cfg)
			return Provisioned{Path: image, Ref: cfg.Name, Stale: err == nil && current != hash}, nil
		}
		if err := h.exec([]string{"sbx", "rm", "-f", cfg.Name}); err != nil {
			return Provisioned{}, failure.New("cannot remove the %s sandbox", cfg.Name).
				WithFix("remove it yourself with 'sbx rm -f %s', then run lid again", cfg.Name)
		}
	}

	if cfg.Template == "" {
		if _, err := template.WriteDockerfile(cfg); err != nil {
			return Provisioned{}, err
		}
	}

	for _, argv := range sbxSteps(cfg) {
		if err := h.exec(argv); err != nil {
			return Provisioned{}, failure.New("%s failed", strings.Join(argv[:2], " ")).
				WithFix("the output above says why; %v", err)
		}
	}

	if err := h.exec(sbxHashArgv(cfg, hash)); err != nil {
		return Provisioned{}, failure.New("cannot record the config hash in the %s sandbox", cfg.Name).
			WithFix("the output above says why; %v", err)
	}

	return Provisioned{Path: image, Ref: cfg.Name, Changed: true}, nil
}

func (s sbx) PrepareAgent(h Host, cfg *config.Config) error {
	if !config.IsClaudeAgent(cfg.Agent) {
		return nil
	}
	if err := sbxApplyTheme(h, cfg); err != nil {
		return err
	}
	if err := sbxApplySettings(h, cfg); err != nil {
		return err
	}
	if err := sbxApplyHandoffSkill(h, cfg); err != nil {
		return err
	}
	return sbxApplyMemory(h, cfg)
}

func sbxApplySettings(h Host, cfg *config.Config) error {
	want := mergeSettings(sbxDefaultSettings(cfg), claudeSettings(cfg))
	if len(want) == 0 {
		return nil
	}

	current, err := h.output(sbxReadSettingsArgv(cfg))
	if err != nil {
		return failure.New("cannot read the agent's settings in the %s sandbox: %s", cfg.Name, firstLine(current)).
			WithFix(sbxExecFix)
	}

	body, changed, err := applySettings(current, want)
	if err != nil || !changed {
		return err
	}

	if out, err := h.output(sbxWriteHomeFileArgv(cfg, claudeSettingsFile, body)); err != nil {
		return failure.New("cannot write the agent's settings in the %s sandbox: %s", cfg.Name, firstLine(out)).
			WithFix("the agent would start with settings %s does not describe", cfg.Ref())
	}
	return nil
}

func sbxApplyTheme(h Host, cfg *config.Config) error {
	body, err := claudeThemeBody(cfg)
	if err != nil || body == "" {
		return err
	}

	if out, err := h.output(sbxWriteHomeFileArgv(cfg, claudeThemeFile, body)); err != nil {
		return failure.New("cannot write the agent's theme in the %s sandbox: %s", cfg.Name, firstLine(out)).
			WithFix("the agent would start on its default theme, not the one %s names", cfg.Ref())
	}
	return nil
}

func sbxApplyMemory(h Host, cfg *config.Config) error {
	memory := strings.TrimSpace(cfg.Memory)
	if memory == "" {
		return nil
	}

	if out, err := h.output(sbxWriteHomeFileArgv(cfg, claudeMemoryFile, memory)); err != nil {
		return failure.New("cannot write the agent's memory in the %s sandbox: %s", cfg.Name, firstLine(out)).
			WithFix("the agent would start without the memory %s gives it", cfg.Ref())
	}
	return nil
}

func sbxApplyHandoffSkill(h Host, cfg *config.Config) error {
	if !cfg.Handoff.Enabled {
		return nil
	}
	return sbxWriteHandoffSkill(h, cfg)
}

func sbxWriteHandoffSkill(h Host, cfg *config.Config) error {
	if out, err := h.output(sbxWriteHomeFileArgv(cfg, handoffSkillFile, handoffSkill)); err != nil {
		return failure.New("cannot write the handoff skill in the %s sandbox: %s", cfg.Name, firstLine(out)).
			WithFix("the agent would not know how to reach the broker %s enables", cfg.Ref())
	}
	return nil
}

func (s sbx) StartArgv(cfg *config.Config, _ string) ([]string, error) {
	return s.startArgv(cfg), nil
}

func (sbx) startArgv(cfg *config.Config) []string {
	return []string{"sbx", "run", "--name", cfg.Name}
}

// ShellArgv opens a shell in the sandbox. The interactive session runs under an
// rc file written into the sandbox's home, which is where the shell: block ends
// up; a one-off command gets the working directory and the sandbox's own login
// environment, but not the aliases — bash does not expand those in a -c string.
//
// The interactive session asks for a pseudo-TTY, without which bash comes up
// with no job control. A command gets stdin but no terminal, so its output can
// still be piped somewhere. Either way the directory is sbx's own -w rather than
// a cd lid writes, so a directory that is not there fails where the user can see
// it instead of leaving the session somewhere else.
func (sbx) ShellArgv(h Host, cfg *config.Config, _ string, command []string) ([]string, error) {
	dir := shellDir(cfg, sbxProjectDir(cfg))

	if len(command) > 0 {
		return []string{"sbx", "exec", "-i", "-w", dir, cfg.Name, "--", "bash", "-lc", shellCommandLine(command)}, nil
	}

	if out, err := h.output(sbxWriteHomeFileArgv(cfg, sbxShellRCFile, shellRC(cfg, ""))); err != nil {
		return nil, failure.New("cannot write the shell's init file in the %s sandbox: %s", cfg.Name, firstLine(out)).
			WithFix(sbxExecFix)
	}
	return []string{"sbx", "exec", "-it", "-w", dir, cfg.Name, "--", "bash", "--rcfile", sbxHome + "/" + sbxShellRCFile, "-i"}, nil
}

// sbxProjectDir is where the project sits inside the sandbox: the workspace when
// one is configured, otherwise the host path the sandbox was created against.
func sbxProjectDir(cfg *config.Config) string {
	if cfg.Workspace != "" {
		return cfg.Workspace
	}
	return cfg.ProjectDir
}

func sbxCommandLine(argv []string) string {
	quoted := make([]string, 0, len(argv))
	for _, arg := range argv {
		if strings.ContainsAny(arg, " \t") {
			arg = fmt.Sprintf("%q", arg)
		}
		quoted = append(quoted, arg)
	}
	return strings.Join(quoted, " ")
}

func sbxSteps(cfg *config.Config) [][]string {
	var steps [][]string
	if cfg.Template == "" {
		tar := sbxImageTar(cfg)
		steps = append(steps,
			template.BuildArgv(cfg),
			[]string{"docker", "image", "save", cfg.SandboxImageName(), "-o", tar},
			[]string{"sbx", "template", "load", tar},
		)
	}

	steps = append(steps, sbxCreateArgv(cfg))

	if allow := sbxNetworkAllow(cfg); len(allow) > 0 {
		steps = append(steps, []string{"sbx", "policy", "allow", "network", "--sandbox", cfg.Name, strings.Join(allow, ",")})
	}

	if cfg.Workspace != "" {
		link := fmt.Sprintf("mkdir -p %q && ln -sfn %q %q", filepath.Dir(cfg.Workspace), cfg.ProjectDir, cfg.Workspace)
		steps = append(steps, []string{"sbx", "exec", "-u", "root", "-w", sbxSelfDir, cfg.Name, "--", "bash", "-c", link})
	}

	if marketplace := dashboardMarketplace(cfg); marketplace != "" {
		steps = append(steps, sbxDashboardShimArgv(cfg, marketplace))
	}

	for _, command := range cfg.Scripts.OnCreate {
		steps = append(steps, []string{"sbx", "exec", cfg.Name, "--", "bash", "-lc", command})
	}

	return steps
}

func sbxDefaultSettings(cfg *config.Config) map[string]any {
	marketplace := dashboardMarketplace(cfg)
	if marketplace == "" {
		return nil
	}
	shim := fmt.Sprintf("%s/.claude/plugins/data/%s-%s/statusline.mjs", sbxHome, dashboardPlugin, marketplace)
	return map[string]any{
		"statusLine": map[string]any{
			"type":    "command",
			"command": fmt.Sprintf("node %q", shim),
		},
	}
}

func sbxDashboardShimArgv(cfg *config.Config, marketplace string) []string {
	cache := fmt.Sprintf("$HOME/.claude/plugins/cache/%s/%s", marketplace, dashboardPlugin)
	data := fmt.Sprintf("$HOME/.claude/plugins/data/%s-%s", dashboardPlugin, marketplace)
	script := fmt.Sprintf(`root=$(ls -d %s/*/ 2>/dev/null | sort -V | tail -1)
root=${root%%/}
hook="$root/hooks/ensure-statusline.mjs"
[ -n "$root" ] && [ -f "$hook" ] || exit 0
CLAUDE_PLUGIN_ROOT="$root" CLAUDE_PLUGIN_DATA=%q node "$hook" || true
`, cache, data)
	return sbxSelfArgv(cfg, script)
}

var sbxAgentHosts = map[string][]string{
	config.AgentClaudeCode: {"api.anthropic.com"},
}

func sbxNetworkAllow(cfg *config.Config) []string {
	var allow []string
	add := func(entry string) {
		if entry != "" && !contains(allow, entry) {
			allow = append(allow, entry)
		}
	}
	for _, host := range sbxAgentHosts[cfg.Agent] {
		add(host)
	}
	for _, domain := range cfg.Network {
		add(domain)
	}
	if cfg.Handoff.Enabled {
		add(handoffResource(cfg))
	}
	for _, b := range cfg.Bridges {
		add(fmt.Sprintf("localhost:%d", b.HostPort))
	}
	return allow
}

func sbxCreateArgv(cfg *config.Config) []string {
	argv := []string{"sbx", "create", "--template", sbxImage(cfg), "--name", cfg.Name}

	// A clone puts the project on the sandbox's own ext4 volume at the same
	// path, rather than sharing the host's copy over virtiofs. The guest can
	// invalidate a virtiofs dentry it still holds, and once it does, getcwd
	// fails for good: bash, git and node all refuse to run in a directory the
	// kernel now calls deleted, and only a restart brings the mount back.
	if cfg.Clone {
		argv = append(argv, "--clone")
	}

	env, err := cfg.ResolvedEnv()
	if err != nil {
		env = map[string]string{}
	}
	for name, value := range handoffEnv(cfg) {
		env[name] = value
	}
	names := make([]string, 0, len(env))
	for name := range env {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		argv = append(argv, "-e", name+"="+env[name])
	}

	for _, port := range cfg.Ports {
		argv = append(argv, "-p", string(port))
	}

	argv = append(argv, "--static-mcp", sbxStaticMCP(cfg))

	return append(argv, cfg.SbxAgent(), cfg.ProjectDir)
}

func sbxStaticMCP(cfg *config.Config) string {
	if len(cfg.MCP) == 0 {
		return "none"
	}
	return strings.Join(cfg.MCP, ",")
}

// sbxSelfDir is where lid runs its own commands in a sandbox. Everything lid
// does for itself works in absolute paths, while the directory a sandbox starts
// in is the project: not mounted yet while one is being created, and no longer
// answering once the guest drops it from the cache behind a shared mount. Naming
// a directory also keeps the runtime off getcwd, which is the call that fails in
// both cases, so lid can still configure an agent and open a shell either way.
const sbxSelfDir = "/"

// sbxExecFix is what to say when a command lid ran in a sandbox came back with
// an error of its own. lid cannot tell a sandbox that is down from one that
// refused the command, so it points at the check and leaves the runtime's own
// words to say the rest.
const sbxExecFix = "'lid status' says whether the sandbox is up; if it is, the line above is why the command could not run in it"

func sbxReadHashArgv(cfg *config.Config) []string {
	return []string{"sbx", "exec", "-w", sbxSelfDir, cfg.Name, "--", "cat", sbxConfigHash}
}

func sbxSelfArgv(cfg *config.Config, script string) []string {
	return []string{"sbx", "exec", "-w", sbxSelfDir, cfg.Name, "--", "bash", "-c", script}
}

func sbxReadSettingsArgv(cfg *config.Config) []string {
	read := fmt.Sprintf("cat %q 2>/dev/null || true", "$HOME/"+claudeSettingsFile)
	return sbxSelfArgv(cfg, read)
}

func sbxWriteHomeFileArgv(cfg *config.Config, rel, body string) []string {
	path := "$HOME/" + rel
	script := fmt.Sprintf(`set -e
mkdir -p %q
cat > %q <<'LID_FILE'
%s
LID_FILE
mv %q %q
`, filepath.Dir(path), path+".lid", strings.TrimRight(body, "\n"), path+".lid", path)
	return sbxSelfArgv(cfg, script)
}

func sbxHashArgv(cfg *config.Config, hash string) []string {
	write := fmt.Sprintf("printf %%s %q > %s", hash, sbxConfigHash)
	return sbxSelfArgv(cfg, write)
}

func sbxImage(cfg *config.Config) string {
	if cfg.Template != "" {
		return cfg.Template
	}
	return cfg.SandboxImageName()
}

func sbxImageTar(cfg *config.Config) string {
	return filepath.Join(os.TempDir(), cfg.SandboxImageName()+".tar")
}

func sbxExists(h Host, cfg *config.Config) bool {
	out, err := h.output([]string{"sbx", "ls", "--quiet"})
	if err != nil {
		return false
	}
	for _, line := range strings.Split(out, "\n") {
		if strings.TrimSpace(line) == cfg.Name {
			return true
		}
	}
	return false
}

func sbxCurrentHash(h Host, cfg *config.Config) (string, error) {
	out, err := h.output(sbxReadHashArgv(cfg))
	if err != nil {
		return "", err
	}
	return strings.TrimSpace(out), nil
}

type sbxSandbox struct {
	ID     string `json:"id"`
	Name   string `json:"name"`
	Status string `json:"status"`
}

func (sbx) Status(h Host, cfg *config.Config, opts StatusOptions) (State, error) {
	out, err := h.output([]string{"sbx", "ls", "--json"})
	if err != nil {
		return State{}, failure.New("cannot list the sandboxes on this machine: %s", firstLine(out)).
			WithFix("check that 'sbx ls' runs, then try again")
	}

	sandboxes, err := parseList[sbxSandbox](out, "sbx ls --json", "sandboxes")
	if err != nil {
		return State{}, err
	}

	for _, sandbox := range sandboxes {
		if sandbox.Name != cfg.Name {
			continue
		}
		state := State{Exists: true, Running: strings.EqualFold(sandbox.Status, "running")}
		if sandbox.ID != "" {
			state.Rows = [][2]string{{"id", sandbox.ID}}
		}
		if opts.Stale && state.Running {
			state.Stale = sbxIsStale(h, cfg)
		}
		return state, nil
	}
	return State{}, nil
}

func (sbx) Stop(h Host, cfg *config.Config) error {
	if err := h.exec([]string{"sbx", "stop", cfg.Name}); err != nil {
		return failure.New("cannot stop the %s sandbox", cfg.Name).
			WithFix("the output above says why; stop it yourself with 'sbx stop %s'", cfg.Name)
	}
	return nil
}

func (sbx) Network(h Host, cfg *config.Config, action NetworkAction, domains []string) error {
	if len(domains) == 0 {
		return nil
	}
	for _, argv := range sbxNetworkArgv(cfg, action, domains) {
		if err := h.exec(argv); err != nil {
			return failure.New("sbx would not %s %s for the %s sandbox", action, strings.Join(domains, ", "), cfg.Name).
				WithFix("the output above says why; 'sbx policy ls' shows the rules already in place")
		}
	}
	return nil
}

func sbxNetworkArgv(cfg *config.Config, action NetworkAction, domains []string) [][]string {
	if action == NetworkRemove {
		argvs := make([][]string, 0, len(domains))
		for _, domain := range domains {
			argvs = append(argvs, []string{"sbx", "policy", "rm", "network", "--sandbox", cfg.Name, "--resource", domain})
		}
		return argvs
	}
	return [][]string{{"sbx", "policy", string(action), "network", "--sandbox", cfg.Name, strings.Join(domains, ",")}}
}

func sbxIsStale(h Host, cfg *config.Config) bool {
	want, err := cfg.FileHash()
	if err != nil {
		return false
	}
	current, err := sbxCurrentHash(h, cfg)
	return err == nil && current != want
}
