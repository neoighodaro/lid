package backend

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/neoighodaro/lid/internal/config"
	"github.com/neoighodaro/lid/internal/failure"
	"github.com/neoighodaro/lid/internal/template"
)

const (
	sbxConfigHash      = "/home/agent/.lid-config-hash"
	claudeSettingsFile = ".claude/settings.json"
	claudeMemoryFile   = ".claude/CLAUDE.md"
)

type sbx struct{}

func (sbx) Name() string { return config.BackendSbx }

func (sbx) EnsureAvailable(h Host) error {
	for _, name := range []string{"sbx", "docker"} {
		if _, err := h.lookPath(name); err != nil {
			return failure.New("%s is not installed", name).
				WithFix("install Docker Sandboxes from https://docs.docker.com/ai/sandboxes/, or set 'backend: %s' to cage a host process instead", config.BackendNono)
		}
	}
	return nil
}

func (sbx) Validate(cfg *config.Config) ([]string, error) {
	set := fieldsSet([]field{
		{"claude.theme", cfg.Claude.Theme != ""},
		{"shell.aliases", len(cfg.Shell.Aliases) > 0 || cfg.Shell.Directory != ""},
		{"memory", cfg.Memory != "" && !config.IsClaudeAgent(cfg.Agent)},
		{"handoff", cfg.Handoff.Enabled},
		{"bridges", len(cfg.Bridges) > 0},
		{"scripts.on_start", len(cfg.Scripts.OnStart) > 0},
	})
	if set == "" {
		return nil, nil
	}
	return []string{fmt.Sprintf("ignoring %s: not wired up for sbx yet", set)}, nil
}

func (s sbx) Render(cfg *config.Config) (string, error) {
	dockerfile, err := template.Render(cfg)
	if err != nil {
		return "", err
	}

	var b strings.Builder
	b.WriteString(dockerfile)
	b.WriteString(fmt.Sprintf("\n# Generated by lid from %s. 'lid start' then runs:\n", cfg.Ref()))
	for _, argv := range append(sbxSteps(cfg), s.startArgv(cfg)) {
		b.WriteString("#   " + sbxCommandLine(argv) + "\n")
	}
	return b.String(), nil
}

func (s sbx) Provision(h Host, cfg *config.Config, opts Options) (Provisioned, error) {
	image := sbxImage(cfg)
	hash, err := cfg.FileHash()
	if err != nil {
		return Provisioned{}, err
	}

	if sbxExists(h, cfg) {
		if !opts.Rebuild {
			current, err := sbxCurrentHash(h, cfg)
			return Provisioned{Path: image, Ref: cfg.Name, Stale: err == nil && current != hash}, nil
		}
		if err := h.exec([]string{"sbx", "rm", "-f", cfg.Name}); err != nil {
			return Provisioned{}, failure.New("cannot remove the %s sandbox", cfg.Name).
				WithFix("remove it yourself with 'sbx rm -f %s', then run lid again", cfg.Name)
		}
	}

	if cfg.Template == "" {
		if _, err := template.WriteDockerfile(cfg); err != nil {
			return Provisioned{}, err
		}
	}

	for _, argv := range sbxSteps(cfg) {
		if err := h.exec(argv); err != nil {
			return Provisioned{}, failure.New("%s failed", strings.Join(argv[:2], " ")).
				WithFix("the output above says why; %v", err)
		}
	}

	if err := h.exec(sbxHashArgv(cfg, hash)); err != nil {
		return Provisioned{}, failure.New("cannot record the config hash in the %s sandbox", cfg.Name).
			WithFix("the output above says why; %v", err)
	}

	return Provisioned{Path: image, Ref: cfg.Name, Changed: true}, nil
}

func (s sbx) PrepareAgent(h Host, cfg *config.Config) error {
	if !config.IsClaudeAgent(cfg.Agent) {
		return nil
	}
	if err := sbxApplySettings(h, cfg); err != nil {
		return err
	}
	return sbxApplyMemory(h, cfg)
}

func sbxApplySettings(h Host, cfg *config.Config) error {
	want := claudeSettings(cfg)
	if len(want) == 0 {
		return nil
	}

	current, err := h.output(sbxReadSettingsArgv(cfg))
	if err != nil {
		return failure.New("cannot read the agent's settings in the %s sandbox: %s", cfg.Name, firstLine(current)).
			WithFix("the sandbox has to be running for lid to configure the agent in it")
	}

	body, changed, err := applySettings(current, want)
	if err != nil || !changed {
		return err
	}

	if out, err := h.output(sbxWriteHomeFileArgv(cfg, claudeSettingsFile, body)); err != nil {
		return failure.New("cannot write the agent's settings in the %s sandbox: %s", cfg.Name, firstLine(out)).
			WithFix("the agent would start with settings %s does not describe", cfg.Ref())
	}
	return nil
}

func sbxApplyMemory(h Host, cfg *config.Config) error {
	memory := strings.TrimSpace(cfg.Memory)
	if memory == "" {
		return nil
	}

	if out, err := h.output(sbxWriteHomeFileArgv(cfg, claudeMemoryFile, memory)); err != nil {
		return failure.New("cannot write the agent's memory in the %s sandbox: %s", cfg.Name, firstLine(out)).
			WithFix("the agent would start without the memory %s gives it", cfg.Ref())
	}
	return nil
}

func (s sbx) StartArgv(cfg *config.Config, _ string) ([]string, error) {
	return s.startArgv(cfg), nil
}

func (sbx) startArgv(cfg *config.Config) []string {
	return []string{"sbx", "run", "--name", cfg.Name}
}

func sbxCommandLine(argv []string) string {
	quoted := make([]string, 0, len(argv))
	for _, arg := range argv {
		if strings.ContainsAny(arg, " \t") {
			arg = fmt.Sprintf("%q", arg)
		}
		quoted = append(quoted, arg)
	}
	return strings.Join(quoted, " ")
}

func sbxSteps(cfg *config.Config) [][]string {
	var steps [][]string
	if cfg.Template == "" {
		tar := sbxImageTar(cfg)
		steps = append(steps,
			template.BuildArgv(cfg),
			[]string{"docker", "image", "save", cfg.SandboxImageName(), "-o", tar},
			[]string{"sbx", "template", "load", tar},
		)
	}

	steps = append(steps, sbxCreateArgv(cfg))

	if len(cfg.Network) > 0 {
		steps = append(steps, []string{"sbx", "policy", "allow", "network", "--sandbox", cfg.Name, strings.Join(cfg.Network, ",")})
	}

	if cfg.Workspace != "" {
		link := fmt.Sprintf("mkdir -p %q && ln -sfn %q %q", filepath.Dir(cfg.Workspace), cfg.ProjectDir, cfg.Workspace)
		steps = append(steps, []string{"sbx", "exec", "-u", "root", cfg.Name, "--", "bash", "-c", link})
	}

	for _, command := range cfg.Scripts.OnCreate {
		steps = append(steps, []string{"sbx", "exec", cfg.Name, "--", "bash", "-lc", command})
	}

	return steps
}

func sbxCreateArgv(cfg *config.Config) []string {
	argv := []string{"sbx", "create", "--template", sbxImage(cfg), "--name", cfg.Name}

	env, err := cfg.ResolvedEnv()
	if err == nil {
		names := make([]string, 0, len(env))
		for name := range env {
			names = append(names, name)
		}
		sort.Strings(names)
		for _, name := range names {
			argv = append(argv, "-e", name+"="+env[name])
		}
	}

	for _, port := range cfg.Ports {
		argv = append(argv, "-p", string(port))
	}

	return append(argv, cfg.SbxAgent(), cfg.ProjectDir)
}

func sbxReadSettingsArgv(cfg *config.Config) []string {
	read := fmt.Sprintf("cat %q 2>/dev/null || true", "$HOME/"+claudeSettingsFile)
	return []string{"sbx", "exec", cfg.Name, "--", "bash", "-c", read}
}

func sbxWriteHomeFileArgv(cfg *config.Config, rel, body string) []string {
	path := "$HOME/" + rel
	script := fmt.Sprintf(`set -e
mkdir -p %q
cat > %q <<'LID_FILE'
%s
LID_FILE
mv %q %q
`, filepath.Dir(path), path+".lid", strings.TrimRight(body, "\n"), path+".lid", path)
	return []string{"sbx", "exec", cfg.Name, "--", "bash", "-c", script}
}

func sbxHashArgv(cfg *config.Config, hash string) []string {
	write := fmt.Sprintf("printf %%s %q > %s", hash, sbxConfigHash)
	return []string{"sbx", "exec", cfg.Name, "--", "bash", "-c", write}
}

func sbxImage(cfg *config.Config) string {
	if cfg.Template != "" {
		return cfg.Template
	}
	return cfg.SandboxImageName()
}

func sbxImageTar(cfg *config.Config) string {
	return filepath.Join(os.TempDir(), cfg.SandboxImageName()+".tar")
}

func sbxExists(h Host, cfg *config.Config) bool {
	out, err := h.output([]string{"sbx", "ls", "--quiet"})
	if err != nil {
		return false
	}
	for _, line := range strings.Split(out, "\n") {
		if strings.TrimSpace(line) == cfg.Name {
			return true
		}
	}
	return false
}

func sbxCurrentHash(h Host, cfg *config.Config) (string, error) {
	out, err := h.output([]string{"sbx", "exec", cfg.Name, "--", "cat", sbxConfigHash})
	if err != nil {
		return "", err
	}
	return strings.TrimSpace(out), nil
}
